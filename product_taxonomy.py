def build_stock_to_products():
    """反查表 {code: [product1, product2, ...]}"""
    m = {}
    for prod, codes in PRODUCT_TAXONOMY.items():
        for c in codes:
            m.setdefault(c, [])
            if prod not in m[c]:
                m[c].append(prod)
    return m


STOCK_TO_PRODUCTS = build_stock_to_products()


def products_of(code):
    return STOCK_TO_PRODUCTS.get(code, [])


